"""exp102: resource-rational meta-control vs fixed confidence threshold.

Synthetic decision-cost benchmark. The ground-truth option accuracies/costs are
generated by the environment, so this tests controller semantics and tradeoffs,
not learned estimation quality.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from tensor_logic.metacognition import (
    ComputationOption,
    MetaState,
    choose_meta_action,
    expected_utility,
    fixed_confidence_policy,
)


def _options(confidence: float, difficulty: float):
    act_accuracy = max(0.5, min(0.99, confidence))
    think_accuracy = min(0.995, act_accuracy + 0.10 + 0.12 * difficulty)
    escalate_accuracy = min(0.999, act_accuracy + 0.18 + 0.16 * difficulty)
    return (
        ComputationOption("ACT", act_accuracy, 0.0),
        ComputationOption("THINK", think_accuracy, 0.05, 0.02),
        ComputationOption("ESCALATE", escalate_accuracy, 0.04, 0.04, 0.08),
    )


def run(seed: int = 11, cases: int = 5000) -> dict:
    rng = random.Random(seed)
    meta_total = 0.0
    threshold_total = 0.0
    meta_counts = {"ACT": 0, "THINK": 0, "ESCALATE": 0}
    threshold_counts = {"ACT": 0, "THINK": 0, "ESCALATE": 0}

    for _ in range(cases):
        confidence = rng.uniform(0.35, 0.98)
        difficulty = rng.random()
        contradiction = min(1.0, difficulty * rng.uniform(0.4, 1.1))
        staleness = rng.random() * difficulty
        error_cost = rng.choice((0.1, 0.5, 1.0, 3.0, 8.0))
        budget = rng.random()

        state = MetaState(
            confidence=confidence,
            contradiction=contradiction,
            source_staleness=staleness,
            error_cost=error_cost,
            compute_budget=budget,
        )
        options = _options(confidence, difficulty)
        option_by_action = {option.action: option for option in options}

        meta = choose_meta_action(state, options)
        threshold = fixed_confidence_policy(confidence)

        meta_counts[meta.action] += 1
        threshold_counts[threshold] += 1
        meta_total += expected_utility(state, option_by_action[meta.action])
        threshold_total += expected_utility(
            state,
            option_by_action[threshold],
        )

    return {
        "experiment": "exp102_metacognition",
        "synthetic_warning": (
            "Option accuracies are environment-known; future work must learn "
            "them under distribution shift."
        ),
        "seed": seed,
        "cases": cases,
        "meta_mean_utility": meta_total / cases,
        "threshold_mean_utility": threshold_total / cases,
        "utility_delta": (meta_total - threshold_total) / cases,
        "meta_action_counts": meta_counts,
        "threshold_action_counts": threshold_counts,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="/tmp/exp102.json")
    args = parser.parse_args()
    result = run()
    Path(args.out).write_text(json.dumps(result, indent=2, sort_keys=True))
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
